"""TelemetryEvent — the contract every telemetry event must satisfy.

Two layers, both driven by the design delivered in the previous project
(docs/telemetry/telemetry-plan.md + event-schemas.json):

1. **Envelope** (Pydantic fields below): eventId, timestamp (ISO 8601 UTC),
   sessionId, userId, event_type (entidad_acción), schemaVersion, requestId,
   context and properties. Typed here so the rest of the backend works with
   real types (UUID, datetime) instead of raw dicts.
2. **Per-event allowlist**: the event is also validated against its own
   definition in ``event-schemas.json`` (``additionalProperties: false`` on
   ``properties``, enums for office/currency/category, office↔currency rule…).
   ``event-schemas.json`` is a byte-identical copy of
   ``docs/telemetry/event-schemas.json``, generated by
   ``docs/telemetry/tools/build_schemas.py`` (``--check`` fails if they diverge).

Usage: ``TelemetryEvent.model_validate(raw_dict)`` raises ``ValidationError``
when the event breaks either layer. The model is the per-item validator of
``POST /telemetry/events`` — never the type of the whole request body.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any, Literal
from uuid import UUID

from jsonschema import Draft7Validator
from pydantic import AwareDatetime, BaseModel, ConfigDict, Field, model_validator

SCHEMA_FILE = Path(__file__).with_name("event-schemas.json")

EventSource = Literal["frontend_backoffice", "frontend_website", "backend_api", "backend_job"]


@lru_cache
def _schema_document() -> dict[str, Any]:
    return json.loads(SCHEMA_FILE.read_text(encoding="utf-8"))


@lru_cache
def _validator_for(event_type: str) -> Draft7Validator | None:
    """Validator for one event definition, with ``$ref`` resolution against
    the whole document (the envelope lives in ``#/definitions/envelope``)."""
    document = _schema_document()
    definitions = document["definitions"]
    if event_type == "envelope" or event_type not in definitions:
        return None
    schema = {**definitions[event_type], "definitions": definitions}
    return Draft7Validator(schema, format_checker=Draft7Validator.FORMAT_CHECKER)


def known_event_types() -> frozenset[str]:
    return frozenset(k for k in _schema_document()["definitions"] if k != "envelope")


def schema_metadata(event_type: str) -> dict[str, Any]:
    """``x-*`` metadata of an event (category, delivery, allowlist…)."""
    return _schema_document()["definitions"][event_type]


class TelemetryContext(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    source: EventSource
    environment: Literal["development", "staging", "production"]
    appVersion: str = Field(pattern=r"^[0-9a-f]{7,12}$")


class TelemetryEvent(BaseModel):
    """Event Envelope v1.0.0 (telemetry-plan.md §4.1) + per-event allowlist."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    eventId: UUID
    timestamp: AwareDatetime
    sessionId: UUID | None
    userId: UUID | None
    event_type: str = Field(pattern=r"^[a-z]+(_[a-z]+)+$")
    schemaVersion: str = Field(pattern=r"^\d+\.\d+\.\d+$")
    requestId: UUID
    context: TelemetryContext
    properties: dict[str, Any]

    @model_validator(mode="before")
    @classmethod
    def _matches_event_schema(cls, raw: Any) -> Any:
        if not isinstance(raw, dict):
            raise ValueError("event must be a JSON object")
        event_type = raw.get("event_type")
        validator = _validator_for(event_type) if isinstance(event_type, str) else None
        if validator is None:
            raise ValueError(f"unknown event_type: {event_type!r}")
        errors = sorted(validator.iter_errors(raw), key=lambda e: list(e.absolute_path))
        if errors:
            # Paths and validator keywords only — never the offending values,
            # which could be PII (telemetry-plan.md §4.5).
            summary = "; ".join(
                f"{'/'.join(map(str, e.absolute_path)) or '<root>'}: {e.validator}" for e in errors[:5]
            )
            raise ValueError(f"event does not match schema of {event_type}: {summary}")
        return raw
